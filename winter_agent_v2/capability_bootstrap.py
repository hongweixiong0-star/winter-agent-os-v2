def write_report(
    root: Path | str,
    scanner: BootstrapScanner,
    *,
    limit: int = 40,
) -> tuple[Path, Path]:
    """Write the scan where any reader -- panel, agent, operator -- can find it.

    Goes under ``learning/`` because that is the project's machine-state area: this
    is a report about the catalog, not a fifth source of truth about capabilities.
    """
    directory = Path(root) / BOOTSTRAP_DIR
    directory.mkdir(parents=True, exist_ok=True)
    payload = scanner.report(limit=limit)
