"""Capability Bootstrap / Preload — "prepare the lesson before the wall".

Why this exists
---------------
Until now V2 could only learn a capability by *hitting the wall*: AUTO fails, the
failure becomes an escalation, a development agent fixes it.  That is the
``LEARN FROM REAL FAILURE`` path and it works, but it is strictly reactive: the
522-row capability catalog has 452 rows the role has never even reached, and no
amount of retrying will ever produce a failure for a route nobody walked.

This module adds the second path, ``PRELOAD BEFORE ENCOUNTER``: continuously scan
the catalog the project already keeps and prepare a *design brief* for the
capabilities that are missing, never tried, defined without an implementation,
covered by an external prior, or sitting on an unwired internal/legacy asset.

What this module is NOT
-----------------------
Not a registry, not a scheduler, not a second development system -- see
``00_MASTER_RULES.md`` §2/§2d.  It is a **projection plus a brief builder**:

* the catalog it scans is ``knowledge/game/capability_catalog.json`` (generated by
  ``tools/build_capability_catalog.py``) and the goal layer is
  ``knowledge/goals/capability_skill_map.json``; it reads both, it owns neither;
* the design drafts it completes are ``skill_factory.PRIORS`` /
  ``dataset/candidate/<SKILL>.json`` -- the existing candidate home;
* in-flight state comes from ``capability_gate.capability_states``, which folds the
  one escalation ledger.  Nothing is stored twice;
* the only thing it *writes* is one escalation record, through
  ``EscalationQueueAdapter.preload()``, into the same ledger, decided by the same
  ``decide()`` throttle, dispatched by the same bridge.  ``PRELOAD`` is an origin,
  not a pipeline.

The two hard ceilings
---------------------
1. **Bootstrap ≠ LIVE_VERIFIED.**  No amount of preparation on this machine can
   promote a capability past ``BOOTSTRAP_MAX_LIFECYCLE``.  Only a production
   episode with a passing verifier does that, in the existing reconciler.
2. **Never an in-flight capability.**  ``WORKING`` / ``DEVELOPMENT_PENDING`` /
   ``CANDIDATE`` / ``LIVE_VERIFY_PENDING`` / ``LIVE_VERIFIED`` are refused by name,
   with the reason recorded, so the same capability cannot be fed to two agents.
"""

