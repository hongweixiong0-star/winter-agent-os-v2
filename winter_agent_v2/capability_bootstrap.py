BOOTSTRAP_DIR = "learning/capability_bootstrap"
REPORT_JSON = "CANDIDATES.json"
REPORT_MD = "CANDIDATES.md"


def write_report(
    root: Path | str,
    scanner: BootstrapScanner,
    *,
    limit: int = 40,
) -> tuple[Path, Path]:
    """Write the scan where any reader -- panel, agent, operator -- can find it.

    Goes under ``learning/`` because that is the project's machine-state area: this
    is a report about the catalog, not a fifth source of truth about capabilities.
    """
    directory = Path(root) / BOOTSTRAP_DIR
    directory.mkdir(parents=True, exist_ok=True)
    payload = scanner.report(limit=limit)
    json_path = directory / REPORT_JSON
    md_path = directory / REPORT_MD
    json_path.write_text(json.dumps(payload, ensure_ascii=False, indent=1), encoding="utf-8")
    md_path.write_text(scanner.markdown(limit=min(limit, 20)), encoding="utf-8")
    return json_path, md_path


def write_brief(root: Path | str, plan: BootstrapPlan) -> Path:
    """Write one capability's brief as JSON, and return its path.

    This is what a development agent is handed, and it is written **before** the
    record reaches the bridge, so the evidence the assignment names exists on disk
    at the moment the assignment is made.
    """
    directory = Path(root) / BOOTSTRAP_DIR / "briefs"
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"{_token_key(plan.code or plan.capability_id)}.json"
    payload = plan.as_row() | {
        "generated_by": "winter_agent_v2.capability_bootstrap",
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "max_lifecycle": BOOTSTRAP_MAX_LIFECYCLE,
        "must_not_claim": list(FORBIDDEN_LIFECYCLES),
        "next_flow": (
            "CANDIDATE -> LIVE_VERIFY_PENDING -> DEVELOPMENT_VALIDATION_DEVICE_LEASE -> "
            "new version active -> V2 unified executor (MAA first) -> real device -> "
            "verifier + evidence -> LIVE_VERIFIED -> gameplay pool"
        ),
    }
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=1), encoding="utf-8")
    return path


def work_order_brief(plan: BootstrapPlan) -> str:
    """The brief as the work order's own text.

    Kept short on purpose: the work order is read by a developer agent that will
    spend its timebox in this repository, so it gets the seven fields, the evidence
    that each one came from, and the ceiling it may not cross.
    """
    lines = [
        "PRELOAD BRIEF (prepared before the encounter; no failure led here)",
        f"capability: {plan.capability_id} {plan.code}",
        f"goal: {plan.goal or '(none mapped)'}   skill: {plan.skill or '(none)'}",
        f"classes: {', '.join(plan.classes)}   risk: {plan.risk}   priority: {plan.priority}",
        f"knowledge source ladder rung: {plan.knowledge_rank} {plan.knowledge_source}",
        "",
        "PIPELINE (run it in this order): REUSE CHECK -> EXTERNAL PRIOR -> MAA TOOL CHECK "
        "-> complete the seven fields -> TARGETED TEST -> CANDIDATE",
        f"  reuse check : {plan.reuse.get('verdict')} "
        f"(registered={plan.reuse.get('skill_registered')}, verifier={plan.reuse.get('verifier_bound')}, "
        f"episodes={plan.reuse.get('episodes')})",
        f"  external    : {plan.external.get('capability') or '(no card in the index)'} "
        f"reuse={plan.external.get('reuse_level') or '-'}",
        f"  MAA check   : {plan.maa.get('verdict')} tools={plan.maa.get('covering_tools')}",
        "",
    ]
    for facet in plan.facets:
        lines.append(f"{facet.name}: {facet.value}  [source={facet.source or '-'} conf={facet.confidence:.2f}]")
    if plan.missing_semantics:
        lines.append("")
        lines.append(f"UNREGISTERED SEMANTICS (need a live frame first): {', '.join(plan.missing_semantics)}")
    if plan.external:
        lines.append("")
        lines.append(
            "EXTERNAL PRIOR (prior only -- adapt, never copy; license "
            f"{plan.external.get('license')}, reuse level {plan.external.get('reuse_level')}): "
            f"{plan.external.get('capability')} @ {plan.external.get('repo')}"
        )
        for source in plan.external.get("source_files") or ():
            lines.append(f"  source file: {source}")
    if plan.notes:
        lines.append("")
        lines.extend(f"NOTE: {note}" for note in plan.notes)
    lines += [
        "",
        f"CEILING: the most this work can produce is {BOOTSTRAP_MAX_LIFECYCLE}. "
        "Do not claim LIVE_TRIED / LIVE_VERIFIED / STABLE -- only a production episode "
        "with a passing verifier recorded after this job does, in the reconciler.",
        "SEE ALSO: docs/ADDING_A_LIVE_ROUTE.md (probe -> templates -> wiring -> live verify), "
        "and write any new measurement back into knowledge/external/external_capability_map.json.",
    ]
    return "\n".join(lines)
