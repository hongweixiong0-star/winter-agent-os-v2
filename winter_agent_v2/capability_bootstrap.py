class BootstrapScanner:
    """Reads what the project already knows, and says what could be preloaded.

    One instance per pass.  Everything is read once in :meth:`load` -- the catalog
    has 522 rows and the naive version re-read a 300 KB manifest per row.
    """

    def __init__(
        self,
        root: Path | str,
        *,
        catalog: Sequence[Mapping[str, Any]] = (),
        catalog_meta: Mapping[str, Any] | None = None,
        goal_skills: Mapping[str, Any] | None = None,
        registry_states: Mapping[str, str] | None = None,
        registry_ids: Iterable[str] = (),
        cards: Sequence[Mapping[str, Any]] = (),
        drafts: Mapping[str, Mapping[str, Any]] | None = None,
        priors: Mapping[str, Any] | None = None,
        verifier_bindings: Iterable[str] = (),
        registered_semantics: Iterable[str] = (),
        asset_names: Iterable[str] = (),
        ledger_index: Mapping[str, tuple[str, str]] | None = None,
        episodes_attempts: Mapping[str, int] | None = None,
        tools: Mapping[str, Any] | None = None,
        now: datetime | None = None,
    ) -> None:
        self.root = Path(root)
        self.catalog = tuple(catalog)
        self.catalog_meta = dict(catalog_meta or {})
        self.goal_skills = dict(goal_skills or {})
        self.registry_states = dict(registry_states or {})
        self.registry_ids = frozenset(str(x) for x in registry_ids)
        self.cards = tuple(cards)
        self.drafts = {str(k): dict(v) for k, v in (drafts or {}).items()}
        self.priors = dict(priors or {})
        self.verifier_bindings = frozenset(str(x) for x in verifier_bindings)
        self.registered_semantics = frozenset(str(x) for x in registered_semantics)
        self.asset_names = tuple(str(x) for x in asset_names)
        self.ledger_index = dict(ledger_index or {})
        self.episodes_attempts = dict(episodes_attempts or {})
        self.tools = dict(tools or {})
        self.now = now or datetime.now(timezone.utc)
        self._asset_stems = frozenset(_token_key(name) for name in self.asset_names)
        self._asset_index = _index_by_token(self.asset_names)
        self._wiki_index = _index_by_token(
            str(path.relative_to(self.root)).replace("\\", "/")
            for folder in ("knowledge/game", "knowledge/ui", "knowledge/events",
                           "knowledge/alliance", "knowledge/combat", "knowledge/heroes",
                           "knowledge/resources")
            for path in (self.root / folder).glob("*.json")
            if path.is_file()
        )
        self._card_index = self._index_cards()

    # -- construction ------------------------------------------------------

    @classmethod
    def load(
        cls,
        root: Path | str | None = None,
        *,
        ledger_snapshot: Any | None = None,
        policy: Any | None = None,
        now: datetime | None = None,
    ) -> "BootstrapScanner":
        """Read every source once.  Missing files degrade to empty, never raise."""
        base = Path(root) if root else Path(__file__).resolve().parents[1]

        catalog_payload = _load_json(base / "knowledge/game/capability_catalog.json") or {}
