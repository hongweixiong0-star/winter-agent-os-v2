def main_loop_status(root: Path | str | None) -> dict[str, Any]:
    """Read the main autonomous-development loop's own ladder, if it exists.

    The operator's rule is "完成自主开发主闭环 P0 后自动启用该 Bootstrap 机制", so
    this reads the loop's status artifact rather than a flag somebody has to
    remember to flip.  A missing artifact is honestly *not* complete.
    """
    base = Path(root) if root else Path(__file__).resolve().parents[1]
    path = base / DEFAULT_P0_PATH
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    return payload if isinstance(payload, dict) else {}


def arm_state(
    root: Path | str | None = None,
    *,
    p0: Mapping[str, Any] | None = None,
) -> tuple[bool, str, str]:
    """``(armed, reason, detail)`` for the preload mechanism.

    Armed means: every stage of the main loop's P0 ladder has reached ``PASS``, so
    the closure the preload feeds has been demonstrated end to end at least once.
    ``config/bootstrap_arm.json`` can override that, explicitly and auditably, so
    an operator can arm it early -- the override is recorded, never silent.
    """
    base = Path(root) if root else Path(__file__).resolve().parents[1]
    ladder = p0 if p0 is not None else main_loop_status(base)
    stages = (ladder or {}).get("stages") or {}
    if stages:
        outstanding = [
            f"{name.split()[0]}={str(body.get('verdict') or '?')}"
            for name, body in stages.items()
            if str((body or {}).get("verdict")) != "PASS"
        ]
        if not outstanding:
            return True, "MAIN_LOOP_P0_PASS", "every stage of the main loop's P0 ladder reads PASS"
        detail = "main loop not fully proven yet: " + ", ".join(outstanding)
    else:
        detail = f"no main-loop status artifact at {DEFAULT_P0_PATH}"

    try:
        override = json.loads((base / DEFAULT_ARM_PATH).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        override = {}

    # ---- P0 ACCEPTANCE SEED (operator §二/§七) -------------------------------------------
    # The cold-start deadlock, stated exactly: the preloader may not dispatch until the main
    # loop is proven, and the main loop cannot be proven until something travels it.  With
    # nothing open -- measured 2026-09-19: current_development_trace() = None and every record
    # terminal (COOLDOWN 2, DONE 9, FAILED 3) -- the loop has no input, so it can never be
    # proven, so the first trace is never dispatched.  Waiting for a random runtime gap turns
    # the acceptance into a coincidence.
    #
    # This is a one-shot exception for that, not a relaxation of the rule.  It is checked
    # *after* the real ladder (a proven loop still wins) and *before* the human override (it is
    # a product mechanism, not an operator decision).  It closes permanently the moment a real
    # production reuse exists -- see `acceptance_seed_allowed`.
    seed_ok, seed_detail = acceptance_seed_allowed(base)
    if seed_ok:
        return True, SEED_ARMED, seed_detail

    if isinstance(override, dict) and override.get("armed"):
        who = str(override.get("armed_by") or "operator")
        why = str(override.get("reason") or "")
        return True, "OPERATOR_OVERRIDE", f"armed by {who}: {why}"

    return False, GATE_NOT_ARMED, detail


#: The gate reason when the one-shot acceptance seed is what armed the preloader.
SEED_ARMED = "P0_ACCEPTANCE_SEED"
#: Written once a real production reuse has been observed.  Its existence closes the seed for
#: good: an exception that stays open becomes the rule.
PROVEN_ONCE_PATH = "learning/knowledge_bootstrap/MAIN_LOOP_PROVEN_ONCE.json"


def acceptance_seed_allowed(root: Path | str | None = None) -> tuple[bool, str]:
    """May the one-shot acceptance seed arm the preloader right now?

    Every condition is read from an artifact rather than passed in, so the answer can be
    reproduced by a reader who was not present -- and so a caller cannot *assert* the conditions
    in order to get the answer it wants.

    Two of the operator's thirteen conditions are deliberately **not** checked here and are
    named so they are not mistaken for enforced ones: the risk tier (T0/T1) and the exclusion of
    the permanent prohibitions are properties of the *candidate*, and are enforced at selection.
    This function answers "is the system in a state where a seed is allowed at all"; the selector
    answers "is this particular capability a lawful one".  Putting the candidate rules here would
    make them look checked while nothing had looked at a candidate yet.
    """
    base = Path(root) if root else Path(__file__).resolve().parents[1]
    proven = base / PROVEN_ONCE_PATH

    try:
        from .escalation_queue import EscalationLedger, current_development_trace
        from .escalation_queue import DEFAULT_LEDGER

        ledger = EscalationLedger(base / DEFAULT_LEDGER)
        rows = ledger.events()
        snapshot = ledger.snapshot()
    except Exception as exc:  # noqa: BLE001 - unreadable state cannot authorise anything
        return False, f"无法读取台账：{type(exc).__name__}: {exc}"

    # §七: proven once, closed forever.  Checked first, and the marker is written the moment the
    # evidence appears rather than on the next start, so the seed cannot survive its own success.
    if any(str(row.get("event")) == "production_reuse" for row in rows):
        try:
            proven.parent.mkdir(parents=True, exist_ok=True)
            proven.write_text(json.dumps({
                "at": datetime.now(timezone.utc).isoformat(),
                "reason": "a real production_reuse exists; P0_ACCEPTANCE_SEED is closed permanently",
            }, ensure_ascii=False, indent=1), encoding="utf-8")
        except OSError:
            pass
        return False, "已出现过真实 production_reuse：P0_ACCEPTANCE_SEED 永久关闭"
    if proven.exists():
        return False, f"{PROVEN_ONCE_PATH} 存在：本次冷启动豁免已经用过"

    # §二 conditions 2-4, 13: nothing open, nothing in flight, and no second seed trace.
    current = current_development_trace(snapshot)
    if current is not None:
        return False, f"已有未完成 trace（{current.key}），不需要种子"
    for state_name in ("WORKING", "SUBMITTED", "NEW", "QUEUED"):
        holders = [r for r in snapshot.records.values() if r.state == state_name]
        if holders:
            return False, f"台账里已有 {state_name} 记录（{holders[0].key}），不需要种子"
    if any(str(r.origin or "") == "bootstrap_seed" for r in snapshot.records.values()):
        return False, "台账里已有 bootstrap_seed 记录：同时只允许一个"

    # §二 condition 5: no examination holding the device.
    try:
        from .device_lease import DeviceLease

        holder = str(DeviceLease(base).holder() or "")
        if holder:
            return False, f"设备租约由 {holder} 持有"
    except Exception:  # noqa: BLE001
        return False, "无法读取设备租约"

    # §二 conditions 6-7: the operator asked for work, and a production window is running it.
    try:
        intent = str(json.loads((base / "config/control_panel_state.json")
                                .read_text(encoding="utf-8")).get("operator_intent") or "")
    except Exception:  # noqa: BLE001
        return False, "无法读取操作员意图"
    if intent.upper() != "RUNNING":
        return False, f"操作员当前为 {intent or '未知'}，种子只在 RUNNING 下生效"
    pump = base / "learning/control_panel/pump.json"
    try:
        age = datetime.now(timezone.utc).timestamp() - pump.stat().st_mtime
    except OSError:
        return False, "没有面板心跳：正式 GUI 未运行"
    if age > 90.0:
        return False, f"面板心跳已过期 {age:.0f}s：正式 GUI 不在运行"

    # §二 condition 9: a healthy gateway, or the first trace would only discover that.
    try:
        gateway = json.loads((base / "learning/control_panel/gateway.json")
                             .read_text(encoding="utf-8"))
    except Exception:  # noqa: BLE001
        return False, "读不到网关探针结果"
    if gateway.get("available") is not True:
        return False, f"网关不是 HEALTHY（{gateway.get('reason') or 'unknown'}）"

    return True, ("冷启动种子条件全部成立：无未完成 trace、无在飞 Job、无租约、"
                  "操作员 RUNNING、生产 GUI 存活、网关 HEALTHY")


def preload_gate(
    *,
    armed: bool,
    arm_reason: str,
    arm_detail: str,
    active_jobs: int,
    pending_records: int,
    lease_holder: str = "",
    runtime: Mapping[str, Any] | None = None,
    actionable: int = 1,
) -> PreloadGate:
    """Whether a preload pass may dispatch anything right now, and why not.

    Pure on purpose: every input is a value some other module already computed, so
    the four things the operator forbids disturbing are visible as four named
    reasons instead of an invisible "we were busy".

    Order matters.  Being unarmed is checked first because it is a statement about
    the whole mechanism, then the four interferences from most severe to least.
    """
    if not armed:
        return PreloadGate(False, arm_reason, arm_detail, armed=False)
    if pending_records > 0:
        return PreloadGate(
            False, GATE_REAL_GAP_WAITING,
            f"{pending_records} record(s) the device already proved are waiting on the queue",
            armed=True,
        )
    if active_jobs > 0:
        return PreloadGate(
            False, GATE_AGENT_SLOT_BUSY,
            f"{active_jobs} development job(s) hold the single slot; a real repair outranks a preload",
            armed=True,
        )
    if lease_holder:
        return PreloadGate(
            False, GATE_DEVICE_LEASED,
            f"the device belongs to {lease_holder}",
            armed=True,
        )
    snapshot = runtime or {}
    goal = str(snapshot.get("current_goal") or "")
    skill = str(snapshot.get("current_skill") or "")
    if goal in REALTIME_GOALS or skill in REALTIME_SKILLS:
        return PreloadGate(
            False, GATE_REALTIME_ACTIVITY,
            f"V2 is running {goal or skill} -- REALTIME, no extra load",
            armed=True,
        )
    if actionable <= 0:
        return PreloadGate(False, GATE_NOTHING_TO_DO, "", armed=True)
    return PreloadGate(True, GATE_OK, "", armed=True)


# ----------------------------------------------------------- small file helpers


def _load_json(path: Path) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None


def _token_key(text: str) -> str:
    return re.sub(r"[^A-Z0-9]+", "_", str(text).upper()).strip("_")


def _tokens(text: str) -> frozenset[str]:
    return frozenset(t for t in _token_key(text).split("_") if t)


def _moment(value: Any) -> datetime | None:
    if not value:
        return None
    try:
        parsed = datetime.fromisoformat(str(value))
    except (TypeError, ValueError):
        return None
    return parsed if parsed.tzinfo else parsed.replace(tzinfo=timezone.utc)


def _index_by_token(names: Iterable[str]) -> dict[str, tuple[tuple[str, frozenset[str]], ...]]:
    """Token -> ``(name, tokens)`` pairs containing it.

    The corpus is thousands of file names and the catalog is 522 rows; testing
    ``tokens <= name`` for every pair would be ~2.6M set operations per scan.  Every
    name is therefore filed under each of its tokens, and a lookup starts from the
    row's *rarest* token -- the smallest bucket, which is the only one that can
    still be a match anyway.
    """
    index: dict[str, list[tuple[str, frozenset[str]]]] = {}
    for name in names:
        tokens = _tokens(name)
        if not tokens:
            continue
        for token in tokens:
            index.setdefault(token, []).append((str(name), tokens))
    return {token: tuple(bucket) for token, bucket in index.items()}


def _rarest_first(
    tokens: Iterable[str],
    index: Mapping[str, Sequence[tuple[str, frozenset[str]]]],
) -> list[tuple[str, frozenset[str]]]:
    """Candidates to test for one query, smallest bucket first."""
    out: list[tuple[str, frozenset[str]]] = []
    seen: set[str] = set()
    for token in sorted(tokens, key=lambda t: len(index.get(t, ()))):
        for name, name_tokens in index.get(token, ()):
            if name in seen:
                continue
            seen.add(name)
            out.append((name, name_tokens))
    return out


def _contained(
    tokens: frozenset[str],
    index: Mapping[str, Sequence[tuple[str, frozenset[str]]]],
) -> str | None:
    """The first indexed name whose whole token-set contains ``tokens``.

    Every token must appear in **one** name -- "the corpus has something named with
    these words".  A bag-of-tokens search across the whole corpus would match
    almost anything and turn "an asset exists" into noise.
    """
    if not tokens:
        return None
    for token in sorted(tokens, key=lambda t: len(index.get(t, ()))):
        for name, name_tokens in index.get(token, ()):
            if tokens <= name_tokens:
                return name
    return None


# ------------------------------------------------------------------- the scan


class BootstrapScanner:
    """Reads what the project already knows, and says what could be preloaded.

    One instance per pass.  Everything is read once in :meth:`load` -- the catalog
    has 522 rows and the naive version re-read a 300 KB manifest per row.
    """

    def __init__(
        self,
        root: Path | str,
        *,
        catalog: Sequence[Mapping[str, Any]] = (),
        catalog_meta: Mapping[str, Any] | None = None,
        goal_skills: Mapping[str, Any] | None = None,
        registry_states: Mapping[str, str] | None = None,
        registry_ids: Iterable[str] = (),
        cards: Sequence[Mapping[str, Any]] = (),
        drafts: Mapping[str, Mapping[str, Any]] | None = None,
        priors: Mapping[str, Any] | None = None,
        verifier_bindings: Iterable[str] = (),
        registered_semantics: Iterable[str] = (),
        asset_names: Iterable[str] = (),
        ledger_index: Mapping[str, tuple[str, str]] | None = None,
        episodes_attempts: Mapping[str, int] | None = None,
        tools: Mapping[str, Any] | None = None,
        now: datetime | None = None,
    ) -> None:
        self.root = Path(root)
        self.catalog = tuple(catalog)
        self.catalog_meta = dict(catalog_meta or {})
        self.goal_skills = dict(goal_skills or {})
        self.registry_states = dict(registry_states or {})
        self.registry_ids = frozenset(str(x) for x in registry_ids)
        self.cards = tuple(cards)
        self.drafts = {str(k): dict(v) for k, v in (drafts or {}).items()}
        self.priors = dict(priors or {})
        self.verifier_bindings = frozenset(str(x) for x in verifier_bindings)
        self.registered_semantics = frozenset(str(x) for x in registered_semantics)
        self.asset_names = tuple(str(x) for x in asset_names)
        self.ledger_index = dict(ledger_index or {})
        self.episodes_attempts = dict(episodes_attempts or {})
        self.tools = dict(tools or {})
        self.now = now or datetime.now(timezone.utc)
        self._asset_stems = frozenset(_token_key(name) for name in self.asset_names)
        self._asset_index = _index_by_token(self.asset_names)
        self._wiki_index = _index_by_token(
            str(path.relative_to(self.root)).replace("\\", "/")
            for folder in ("knowledge/game", "knowledge/ui", "knowledge/events",
                           "knowledge/alliance", "knowledge/combat", "knowledge/heroes",
                           "knowledge/resources")
            for path in (self.root / folder).glob("*.json")
            if path.is_file()
        )
        self._card_index = self._index_cards()

    # -- construction ------------------------------------------------------

    @classmethod
    def load(
        cls,
        root: Path | str | None = None,
        *,
        ledger_snapshot: Any | None = None,
        policy: Any | None = None,
        now: datetime | None = None,
    ) -> "BootstrapScanner":
        """Read every source once.  Missing files degrade to empty, never raise."""
        base = Path(root) if root else Path(__file__).resolve().parents[1]

        catalog_payload = _load_json(base / "knowledge/game/capability_catalog.json") or {}
        goal_map = _load_json(base / "knowledge/goals/goal_capability_map.json") or {}
        cards = (_load_json(base / "knowledge/external/external_capability_map.json") or {}).get("capabilities") or []
        tools = _load_json(base / "knowledge/tooling/tool_registry.json") or {}

        registry_states: dict[str, str] = {}
        registry_ids: list[str] = []
        try:
            import sys

            if str(base) not in sys.path:
                sys.path.insert(0, str(base))
            from .skills import v2_registry

            for skill in v2_registry().all():
                state = getattr(skill.state, "value", skill.state)
                registry_states[str(skill.id)] = str(state)
                registry_ids.append(str(skill.id))
        except Exception:  # noqa: BLE001 - a scan must not need an importable registry
            pass

        try:
            from .runtime import LiveRuntime

            bindings = tuple(str(k) for k in LiveRuntime.VERIFIED_ATOMIC)
        except Exception:  # noqa: BLE001
            bindings = ()

        from .skill_factory import PRIORS

        drafts: dict[str, Mapping[str, Any]] = {}
        candidate_dir = base / "dataset/candidate"
        if candidate_dir.is_dir():
            for path in sorted(candidate_dir.glob("*.json")):
                payload = _load_json(path)
                if isinstance(payload, dict) and payload.get("lifecycle"):
                    drafts[path.stem] = payload

        manifest = _load_json(base / "dataset/candidate/template_manifest.json") or {}
        semantics = [
            str(row.get("semantic"))
            for row in (manifest.get("records") or [])
            if isinstance(row, Mapping) and row.get("semantic")
        ]

        asset_names: list[str] = []
        for folder in ("dataset/truth_audit", "evidence", "knowledge/skills",
                       "dataset/candidate", "knowledge/failure_patterns"):
            directory = base / folder
            if not directory.is_dir():
                continue
            for path in directory.rglob("*"):
                if path.is_file():
                    asset_names.append(path.name)
        asset_names.append("legacy:" + str(base.parent / "dongri-mumu-bot"))

        ledger_index: dict[str, tuple[str, str]] = {}
        try:
            from .capability_gate import capability_states

            snapshot = ledger_snapshot
            if snapshot is None:
                from .escalation_queue import DEFAULT_LEDGER, EscalationLedger, fold

                snapshot = fold(EscalationLedger(base / DEFAULT_LEDGER).events())
            if policy is None:
                from .escalation_queue import EscalationPolicy

                policy = EscalationPolicy()
            for record in snapshot.records.values():
                state = capability_states({record.key: record}, now=now or datetime.now(timezone.utc),
                                          policy=policy)
                for capability, (value, reason, _until) in state.items():
                    ledger_index[capability] = (value, reason)
        except Exception:  # noqa: BLE001 - an unreadable ledger means "nothing in flight"
            ledger_index = {}

        attempts: dict[str, int] = {}
        episodes = base / "learning/episodes.jsonl"
        if episodes.is_file():
            try:
                for line in episodes.read_text(encoding="utf-8", errors="replace").splitlines():
                    line = line.strip()
                    if not line.startswith("{"):
                        continue
                    try:
                        row = json.loads(line)
                    except json.JSONDecodeError:
                        continue
                    if not row.get("recorded_at"):
                        continue
                    skill = str(row.get("skill") or "")
                    if skill:
                        attempts[skill] = attempts.get(skill, 0) + 1
            except OSError:
                attempts = {}

        return cls(
            base,
            catalog=catalog_payload.get("capabilities") or (),
            catalog_meta={k: v for k, v in catalog_payload.items() if k != "capabilities"},
            goal_skills=goal_map,
            registry_states=registry_states,
            registry_ids=registry_ids,
            cards=cards,
            drafts=drafts,
            priors=PRIORS,
            verifier_bindings=bindings,
            registered_semantics=semantics,
            asset_names=asset_names,
            ledger_index=ledger_index,
            episodes_attempts=attempts,
            tools=tools,
            now=now,
        )

    # -- indexes -----------------------------------------------------------

    def _index_cards(self) -> dict[str, Mapping[str, Any]]:
        """External cards by the catalog row they name.

        The map's ``v2_equivalent`` is free text (``"CAP-B09/B10 VIP (no skill yet;
        entry never found)"``), so this indexes on the ``CAP-`` ids inside it -- the
        ids are the one machine-readable handhold the map actually has.
        """
        index: dict[str, list[Mapping[str, Any]]] = {}
        for card in self.cards:
            blob = " ".join(
                str(card.get(key) or "")
                for key in ("v2_equivalent", "capability", "current_gap", "implementation_summary")
            )
            for token in set(re.findall(r"CAP-[A-Z]{1,2}\d{1,2}", blob.upper())):
                index.setdefault(token, []).append(card)
        return {k: v[0] for k, v in index.items()}

    def _goal_names_for_skill(self, skill: str) -> tuple[str, ...]:
        """Which goals the project itself says this skill serves."""
        found: list[str] = []
        for goal, body in self.goal_skills.get("goals", {}).items():
            for entry in (body or {}).get("capabilities") or ():
                names = [entry.get("implemented_by"), entry.get("live_verified_by")]
                names += list(entry.get("alternatives") or ())
                if skill and skill in [str(n) for n in names if n]:
                    found.append(str(goal))
        return tuple(dict.fromkeys(found))

    def _sibling_observed(self, category: str) -> bool:
        """Has the role ever shown this feature family?

        The only honest source of "unlocked" this project has: the catalog records
        ``implementation_status``/``lifecycle`` per row, and a family in which at
        least one row has a real live attempt is a family the client has already
        shown.  Everything else stays UNKNOWN -- claiming a feature is unlocked
        because a wiki says so would be prior knowledge outranking evidence.
        """
        for row in self.catalog:
            if str(row.get("category") or "") != category:
                continue
            if str(row.get("implementation_status")) == "EXISTING":
                return True
            if int(row.get("live_attempts") or 0) > 0:
                return True
        return False

    def _match_card(self, row: Mapping[str, Any]) -> Mapping[str, Any]:
        direct = self._card_index.get(str(row.get("capability_id") or "").upper())
        if direct:
            return direct
        code = _tokens(row.get("code"))
        best: Mapping[str, Any] = {}
        best_overlap = 0
        for card in self.cards:
            overlap = len(code & _tokens(card.get("capability") or ""))
            if overlap > best_overlap:
                best, best_overlap = card, overlap
        return best if best_overlap >= 2 else {}

    def _match_draft(self, row: Mapping[str, Any]) -> tuple[str, Mapping[str, Any], bool]:
        """``(skill_id, draft, exact)`` -- the design this row can work from.

        ``exact`` distinguishes "this capability already has a draft" from "a
        *related* capability's draft is informative".  The distinction matters: a
        near-match like ``CLAIM_REWARD`` against ``CLAIM_FREE_REWARD`` gives the seven
        fields something to start from, but it is a hypothesis about a different
        screen, so it may inform a brief and may never make one look designed.
        """
        code = str(row.get("code") or "")
        existing = str(row.get("existing_skill") or "")
        for key in (existing, code):
            if not key:
                continue
            if key in self.drafts:
                return key, self.drafts[key], True
            if key in self.priors:
                return key, {}, True
        # Conservative token match: a multi-token name must be contained in the
        # other, and a single-token name must be the whole other name -- otherwise
        # "RESEARCH" would adopt any skill with the word in it.
        code_tokens = _tokens(code)
        if len(code_tokens) < 2:
            return "", {}, False
        for skill_id in list(self.priors) + list(self.drafts):
            other = _tokens(skill_id)
            if len(other) >= 2 and (other <= code_tokens or code_tokens <= other):
                return skill_id, self.drafts.get(skill_id, {}), False
        return "", {}, False

    # -- classification ----------------------------------------------------

    def _in_flight(self, row: Mapping[str, Any], skill: str) -> tuple[str, str]:
        """The five states that forbid a second Bootstrap, plus the two settled ones.

        Checked against *both* vocabularies -- the catalog's ``code`` and the
        capability layer the ledger speaks -- because the ledger is keyed on the
        capability name from ``capability_skill_map.json`` while the catalog is keyed
        on its own code, and only testing one of them would let the same capability
        reach two agents through two names.
        """
        variants = {
            str(row.get("code") or ""),
            str(row.get("capability_id") or ""),
            skill,
            str(row.get("existing_skill") or ""),
            *self._goal_names_for_skill(skill),
        }
        variants.discard("")
        for name in variants:
            hit = self.ledger_index.get(name)
            if hit:
                state, reason = hit
                if state == "LIVE_VERIFIED":
                    return "LIVE_VERIFIED", reason
                if state == "DEVELOPMENT_PENDING":
                    return "DEVELOPMENT_PENDING", reason
                if state == "COOLDOWN":
                    return "COOLDOWN", f"a job already spent the repair budget: {reason}"
                if state == "BLOCKED":
                    return "BLOCKED", f"already escalated and blocked: {reason}"
                if state == "RUNNABLE" and "live verification" in reason:
                    return "LIVE_VERIFY_PENDING", reason

        for name in (skill, str(row.get("existing_skill") or "")):
            state = self.registry_states.get(name, "")
            if state == "CANDIDATE":
                return "CANDIDATE", f"{name} is a registered candidate awaiting its live try"
            if state == "BLOCKED":
                return "BLOCKED", f"{name} is registered as BLOCKED in the one registry"
            if state in ("VERIFIED", "STABLE"):
                return "LIVE_VERIFIED" if state == "VERIFIED" else "STABLE", (
                    f"{name} is already {state} in the one registry"
                )
        if skill and skill in self.drafts:
            return "CANDIDATE", f"a design draft already exists at dataset/candidate/{skill}.json"
        if str(row.get("lifecycle")) == "DEGRADED" or (
            str(row.get("implementation_status")) == "EXISTING"
            and int(row.get("live_failure") or 0) >= DEGRADED_MIN_FAILURES
        ):
            # Implemented, and measurably worse than it was.  Its repair is the runtime
            # path (a real failure already exists, with an episode behind it), so a
            # preload would be the second job the operator forbids -- but the refusal
            # says *why*, so a reader does not have to guess.
            return "DEGRADED", (
                f"the catalog records {int(row.get('live_failure') or 0)} real failures for an "
                f"implemented capability: this is a repair with failure evidence, not a preload"
            )
        return "", ""

    def _classes(self, row: Mapping[str, Any], skill: str, card: Mapping[str, Any],
                 draft: Mapping[str, Any], has_prior: bool = False) -> tuple[str, ...]:
        found: list[str] = []
        implemented = str(row.get("implementation_status")) == "EXISTING"
        attempts = int(row.get("live_attempts") or 0)
        if not implemented and not skill:
            if draft or card or has_prior:
                pass  # named by a more specific class below
            else:
                found.append(CLASS_MISSING)
        if implemented and attempts == 0:
            found.append(CLASS_NEVER_TRIED)
        if (draft or has_prior) and not implemented and not skill:
            found.append(CLASS_DEFINED_NO_IMPLEMENTATION)
        if card and not implemented and not skill:
            found.append(CLASS_EXTERNAL_PRIOR_UNIMPLEMENTED)
        if not implemented and not skill and self._has_asset(row):
            found.append(CLASS_LEGACY_ASSET_UNWIRED)
        if str(row.get("lifecycle")) == "DEGRADED" or (
            implemented and int(row.get("live_failure") or 0) >= DEGRADED_MIN_FAILURES
        ):
            # "因 UI 变化而 DEGRADED" is a *repair* (route B), so this is named for
            # visibility and refused as a preload below.  The catalog never emits the
            # DEGRADED lifecycle today, so the real signal is its own failure count --
            # the same threshold the project's ``degraded_min_failures`` names.
            found.append(CLASS_DEGRADED)
        return tuple(found)

    def _has_asset(self, row: Mapping[str, Any]) -> bool:
        """Is there already an internal/Legacy artefact for this capability?

        Strict on purpose: every token of the catalog code must appear in **one**
        existing file name.  A bag-of-tokens search over the whole corpus matches
        almost everything, and "an asset exists but is unwired" would then mean
        nothing at all.
        """
        tokens = _tokens(row.get("code"))
        if len(tokens) >= 2:
            return bool(_contained(tokens, self._asset_index))
        stem = _token_key(row.get("code"))
        return bool(stem) and stem in self._asset_stems

    def _wiki_files(self, row: Mapping[str, Any]) -> tuple[str, ...]:
        """The in-project game knowledge that should be read before exploring.

        This is ladder rung 5 (game database / wiki / guide), and in this project it
        is a real local corpus -- ``knowledge/game/*.json`` is the canonical map.  A
        pointer is not knowledge, so this never fills a field; it says where the next
        attempt should read, and rung 6 (self-exploration) is only reached when even
        that is empty.
        """
        tokens = _tokens(row.get("code"))
        if not tokens:
            return ()
        found: list[str] = []
        for name, name_tokens in _rarest_first(tokens, self._wiki_index):
            if tokens & name_tokens:
                found.append(name)
            if len(found) >= 3:
                break
        return tuple(found)

    def _priority(
        self,
        row: Mapping[str, Any],
        classes: Sequence[str],
        unlocked: str,
        goal_names: Sequence[str] = (),
    ) -> str:
        """The operator's P0..P5 rung for one row.

        "预计即将解锁" (P4) is deliberately **not** guessed from the catalog's tree
        order.  An earlier version demoted every row that sat behind the first hole in
        its category, which made all of category A "not yet" -- a claim about role
        progression that the catalog does not actually support (its ``unlock_status``
        is UNKNOWN for all 522 rows).  What the project *can* justify is: a capability
        no goal names, in a family the role has never shown, is future work; one that a
        goal V2 already runs names is work we will need, so it is P4 rather than P5.
        """
        if unlocked != "OBSERVED":
            return PRIO_NEAR_UNLOCK if goal_names else PRIO_FUTURE_LOCKED
        risk = str(row.get("risk") or "")
        if not str(row.get("implementation_status")) == "EXISTING":
            return PRIO_UNLOCKED_MISSING
        if risk in FREE_RISKS and str(row.get("real_money_cost")) == "NONE_ALLOWED":
            return PRIO_HIGH_FREQ_FREE_VALUE
        return PRIO_OTHER_UNLOCKED

    # -- facets ------------------------------------------------------------

    def _card_value(self, card: Mapping[str, Any], key: str) -> str:
        value = card.get(key)
        return str(value).strip() if value else ""

    def _facets(
        self,
        row: Mapping[str, Any],
        skill: str,
        card: Mapping[str, Any],
        draft: Mapping[str, Any],
        prior: Any,
    ) -> tuple[Facet, ...]:
        """The operator's seven fields, each with the highest-ranked source that has it.

        Filled in ladder order: V2's own evidence first, then the draft the project
        generated, then Legacy/measured assets, then the external prior.  A field
        with no source stays ``UNKNOWN`` -- and it is the unknown fields that decide
        the plan state, so a brief cannot look complete by being vague.
        """
        goal = ", ".join(self._goal_names_for_skill(skill)) or ""
        verifier_name = ""
        for binding in sorted(self.verifier_bindings):
            if skill and (binding == skill or skill in binding):
                verifier_name = binding
                break
        semantics = tuple(getattr(prior, "required_semantics", ()) or ()) if prior else ()
        semantics = semantics or tuple(str(s) for s in (draft.get("semantic_requirements") or ()))
        missing = tuple(s for s in semantics if s not in self.registered_semantics)

        def pick(*options: tuple[str, str, float]) -> Facet:
            """First option with content wins; the ladder is the argument order."""
            for value, source, confidence in options:
                if value and value != UNKNOWN:
                    return Facet("", value, source, confidence)
            return Facet("", UNKNOWN)

        preconditions = pick(
            (", ".join(str(x) for x in (draft.get("preconditions") or ())),
             SRC_V2_EVIDENCE, 0.6) if draft else ("", "", 0.0),
            (f"从 {', '.join(tuple(getattr(prior, 'entry_pages', ()) or ()))} 出发"
             if prior and getattr(prior, "entry_pages", ()) else "",
             SRC_V2_EVIDENCE, 0.5),
            (self._card_value(card, "preconditions"), SRC_EXTERNAL_MAP, 0.3),
        )
        navigation = pick(
            (" -> ".join(tuple(getattr(prior, "entry_pages", ()) or ())
                        + tuple(getattr(prior, "target_pages", ()) or ()))
             if prior else "", SRC_V2_EVIDENCE, 0.55),
            (self._card_value(card, "navigation"), SRC_EXTERNAL_MAP, 0.45),
            (goal and f"目标 {goal} 的既有路线（见 knowledge/skills）", SRC_GAME_DB_WIKI, 0.3),
        )
        recognition = pick(
            (", ".join(semantics), SRC_V2_EVIDENCE, 0.5 if not missing else 0.3),
            (self._card_value(card, "recognition"), SRC_EXTERNAL_MAP, 0.4),
            (("dataset/truth_audit 与 dataset/candidate 中有同名资产，可先量再设计"
              if self._has_asset(row) else ""), SRC_LEGACY_ASSET, 0.2),
        )
        action = pick(
            (", ".join(str(x) for x in (getattr(prior, "execute_steps", ()) or ())),
             SRC_V2_EVIDENCE, 0.55),
            (self._card_value(card, "action"), SRC_EXTERNAL_MAP, 0.45),
        )
        verifier = pick(
            (f"VERIFIED_ATOMIC[{verifier_name}]" if verifier_name else "", SRC_V2_EVIDENCE, 0.8),
            (", ".join(str(x) for x in (getattr(prior, "success_conditions", ()) or ())),
             SRC_V2_EVIDENCE, 0.4),
            (self._card_value(card, "verification"), SRC_EXTERNAL_MAP, 0.25),
        )
        recovery = pick(
            (", ".join(str(x) for x in (draft.get("recovery") or ())), SRC_V2_EVIDENCE, 0.5),
            (self._card_value(card, "recovery"), SRC_EXTERNAL_MAP, 0.35),
        )
        risk = pick(
            (f"{row.get('risk')}（总表判定，资源成本 {row.get('resource_cost')}）",
             SRC_V2_EVIDENCE, 0.7),
        )
        if self._card_value(card, "reuse_level"):
            risk = Facet(
                risk.name, risk.value,
                f"{risk.source} + {SRC_EXTERNAL_MAP}"
                f"（沿用等级 {card.get('reuse_level')}，许可证 {card.get('license')}）",
                risk.confidence,
            )

        ordered = (preconditions, navigation, recognition, action, verifier, recovery, risk)
        return tuple(
            Facet(name, facet.value, facet.source, facet.confidence)
            for name, facet in zip(FACET_NAMES, ordered)
        )

    # -- the plan ----------------------------------------------------------

    def _maa_check(self, row: Mapping[str, Any]) -> dict[str, Any]:
        """The MAA TOOL CHECK, read from the project's own tool registry.

        The operator's §2b rule is "先找工具，再写代码".  The registry already records
        what is installed and verified, so the check is a lookup rather than a
        rediscovery -- and the answer for anything touching capture / locate /
        click is "MAA", which is also what the row's own ``preferred_backend`` says.
        """
        entries = [t for t in (self.tools.get("tools") or []) if isinstance(t, Mapping)]
        covering = [
            str(t.get("tool_id")) for t in entries
            if str(t.get("tool_id")) in ("MAA_FRAMEWORK", "RAPID_OCR")
            or "OCR" in str(t.get("tool_id")).upper()
            or "RapidOCR" in str(t.get("name"))
        ]
        return {
            "declared_backend": str(row.get("preferred_backend") or ""),
            "covering_tools": covering,
            "custom_code_needed": (
                "模板 / 页面模型 / 锚点 / Verifier 及其证据 —— MAA 只提供引擎，"
                "不提供《无尽冬日》的游戏知识（§2b）"
            ),
            "verdict": "USE_MAA_PLUS_V2_VISION" if covering else "TOOL_REGISTRY_UNREADABLE",
        }

    def _reuse_check(self, row: Mapping[str, Any], skill: str) -> dict[str, Any]:
        """The 2-minute Reuse Check, evaluated from the same five sources.

        Same rule as ``tools/reuse_check.py``: a local route means the external
        search does not happen at all.
        """
        registered = skill in self.registry_ids
        verifier = any(skill and (b == skill or skill in b) for b in self.verifier_bindings)
        draft = skill in self.drafts
        return {
            "skill_registered": registered,
            "verifier_bound": verifier,
            "design_draft": draft,
            "episodes": self.episodes_attempts.get(skill, 0),
            "local_path_exists": bool(verifier and (registered or draft)),
            "verdict": (
                "REUSE_LOCAL" if (verifier and (registered or draft))
                else "NO_LOCAL_PATH_ESCALATE"
            ),
        }

    def _targeted_test(
        self,
        row: Mapping[str, Any],
        skill: str,
        facets: Sequence[Facet],
        missing: Sequence[str],
        verifier_bound: bool,
    ) -> dict[str, Any]:
        """What can be tested *on this machine*, and what cannot.

        Offline the only honest test is design completeness: every field sourced,
        every required semantic registered, a verifier bound.  The live test is
        named too -- and it is not run here, because a preload never touches the
        device (operator §7: Bootstrap is background and low priority).
        """
        unknown = [f.name for f in facets if not f.known]
        design_complete = not unknown and not missing and verifier_bound
        return {
            "name": "DESIGN_COMPLETE",
            "verdict": "PASS" if design_complete else "NOT_PROVEN",
            "detail": (
                "七个字段均有来源、语义已注册、verifier 已绑定"
                if design_complete else
                f"缺字段 {unknown or '-'}；未注册语义 {list(missing) or '-'}；"
                f"verifier {'已绑定' if verifier_bound else '未绑定'}"
            ),
            "live_test_deferred_to": (
                f"run_live.py --goal {', '.join(self._goal_names_for_skill(skill))}"
                if skill and self._goal_names_for_skill(skill)
                else "先取得一帧真机页面（只读探针），再设计缺失的语义"
            ),
        }

    def _plan(self, row: Mapping[str, Any]) -> BootstrapPlan:
        skill = str(row.get("code") or "")
        existing = str(row.get("existing_skill") or "")
        draft_skill, draft, exact = self._match_draft(row)
        skill = existing or draft_skill or skill
        prior = self.priors.get(draft_skill or existing) or self.priors.get(skill)
        card = self._match_card(row)
        classes = self._classes(row, existing, card, draft, has_prior=bool(prior))
        unlocked = "OBSERVED" if (
            str(row.get("current_role_available")) == "OBSERVED_AVAILABLE"
            or self._sibling_observed(str(row.get("category") or ""))
        ) else "UNKNOWN"
        goal_names = self._goal_names_for_skill(skill)
        priority = self._priority(row, classes, unlocked, goal_names)
        facets = self._facets(row, skill, card, draft, prior)
        state, reason = self._in_flight(row, skill)

        semantics = tuple(getattr(prior, "required_semantics", ()) or ()) if prior else ()
        semantics = semantics or tuple(str(s) for s in (draft.get("semantic_requirements") or ()))
        missing = tuple(s for s in semantics if s not in self.registered_semantics)
        verifier_bound = any(skill and (b == skill or skill in b) for b in self.verifier_bindings)
        reuse = self._reuse_check(row, skill)
        maa = self._maa_check(row)
        targeted = self._targeted_test(row, skill, facets, missing, verifier_bound)

        if state:
            plan_state = IN_FLIGHT
        elif any(not f.known for f in facets):
            plan_state = NEEDS_LIVE_FRAME
        elif not exact:
            # Every field came from a *related* capability's draft.  That is a
            # hypothesis about a different screen, so it is a brief, not a design.
            plan_state = NEEDS_LIVE_FRAME
        elif targeted["verdict"] == "PASS":
            plan_state = READY_FOR_LIVE_VERIFY
        else:
            plan_state = DRAFT

        # The knowledge source a preload would actually design *from*.  ``Risk`` is
        # excluded on purpose: it is catalog metadata that every row has, so counting
        # it would rank all 522 rows as "V2 evidence" and make the ladder say nothing.
        # When no field has a source, the ladder still answers -- rung 5 names the
        # in-project knowledge file to read first, rung 6 is the live probe.
        design_sources = [f.source for f in facets if f.name != "Risk" and f.known and f.source]
        wiki = self._wiki_files(row)
        if design_sources:
            knowledge_source = min(design_sources, key=knowledge_rank)
        else:
            knowledge_source = SRC_GAME_DB_WIKI if wiki else SRC_SELF_EXPLORATION

        goal_names = self._goal_names_for_skill(skill)
        goal_names = self._goal_names_for_skill(skill)
        # Tier first, then "how cheap is this preload, and how much does it unblock".
        # The tier gap (60 points between the top and bottom rung) is wider than the
        # sum of every bonus below, so the operator's order is preserved and the
        # tie-breaks only order within a rung -- which is why they can be generous.
        score = PRIORITY_WEIGHT.get(priority, 0.0)
        score += float(len(KNOWLEDGE_LADDER) + 1 - knowledge_rank(knowledge_source)) * 6.0
        score += 3.0 * min(len(goal_names), 4)
        if str(row.get("risk")) in FREE_RISKS and str(row.get("real_money_cost")) == "NONE_ALLOWED":
            score += FREE_BONUS
        if classes:
            score += 2.0
        if reuse["verifier_bound"]:
            score += 3.0

        notes: list[str] = []
        if draft_skill and not exact:
            notes.append(
                f"字段来自相近技能 {draft_skill} 的草稿（不是本能力的实现）——必须真机校准后才算设计"
            )
        if wiki and not design_sources:
            notes.append(f"先读项目内知识：{', '.join(wiki)}（第 5 级）；读不到再上真机探针")
        elif not design_sources:
            notes.append("任何一级知识都没有来源 —— 只能先取一帧真机页面（第 6 级，最后手段）")
        if missing:
            notes.append(f"未注册语义 {list(missing)} —— 需要一帧真机页面才能设计（只读探针）")
        if card and str(card.get("reuse_level")) in ("LICENSE_BLOCKED", "NOT_USEFUL"):
            notes.append(f"外部沿用等级 {card.get('reuse_level')}：只作玩法/UI 先验，不复制任何代码")

        return BootstrapPlan(
            capability_id=str(row.get("capability_id") or ""),
            code=str(row.get("code") or ""),
            goal=", ".join(self._goal_names_for_skill(skill)),
            skill=skill,
            classes=classes or (CLASS_MISSING,),
            priority=priority,
            score=score,
            plan_state=plan_state,
            knowledge_source=knowledge_source,
            knowledge_rank=knowledge_rank(knowledge_source),
            facets=facets,
            in_flight=state,
            in_flight_reason=reason,
            risk=str(row.get("risk") or ""),
            unlocked=unlocked,
            existing_skill=existing,
            has_verifier=verifier_bound,
            missing_semantics=missing,
            reuse=reuse,
            external=(
                {
                    "capability": card.get("capability"),
                    "repo": card.get("repo"),
                    "reuse_level": card.get("reuse_level"),
                    "license": card.get("license"),
                    "source_files": list(card.get("source_files") or ())[:4],
                    "current_gap": card.get("current_gap"),
                } if card else {}
            ),
            maa=maa,
            targeted_test=targeted,
            notes=tuple(notes),
        )

    # -- public ------------------------------------------------------------

    def plans(self) -> tuple[BootstrapPlan, ...]:
        return tuple(self._plan(row) for row in self.catalog)

    def candidates(self) -> tuple[BootstrapPlan, ...]:
        """Actionable plans, best first.  The only input to a preload pass."""
        rows = [p for p in self.plans() if p.actionable]
        rows.sort(key=lambda p: (-p.score, p.capability_id))
        return tuple(rows)

    def report(self, *, limit: int = 40) -> dict[str, Any]:
        plans = self.plans()
        actionable = [p for p in plans if p.actionable]
        by_priority: dict[str, int] = {}
        by_state: dict[str, int] = {}
        by_class: dict[str, int] = {}
        by_source: dict[str, int] = {}
        for plan in plans:
            by_priority[plan.priority] = by_priority.get(plan.priority, 0) + 1
            by_state[plan.plan_state] = by_state.get(plan.plan_state, 0) + 1
            by_source[plan.knowledge_source] = by_source.get(plan.knowledge_source, 0) + 1
            for name in plan.classes:
                by_class[name] = by_class.get(name, 0) + 1
        ranked = sorted(actionable, key=lambda p: (-p.score, p.capability_id))
        return {
            "schema_version": "1.0",
            "generated_by": "winter_agent_v2.capability_bootstrap",
            "generated_at": self.now.isoformat(),
            "policy": {
                "max_lifecycle": BOOTSTRAP_MAX_LIFECYCLE,
                "never_from_a_bootstrap": list(FORBIDDEN_LIFECYCLES),
                "knowledge_ladder": list(KNOWLEDGE_LADDER),
                "priority_ladder": list(PRIORITY_LADDER),
                "classes": list(BOOTSTRAP_CLASSES),
                "fields": list(FACET_NAMES),
            },
            "summary": {
                "catalog_rows": len(plans),
                "actionable": len(actionable),
                "in_flight": len(plans) - len(actionable),
                "by_priority": by_priority,
                "by_plan_state": by_state,
                "by_class": by_class,
                "by_knowledge_source": by_source,
            },
            "candidates": [p.as_row() for p in ranked[:limit]],
        }

    def markdown(self, *, limit: int = 12) -> str:
        report = self.report(limit=limit)
        summary = report["summary"]
        lines = [
            "# Capability Bootstrap / Preload —— 候选（自动生成）",
            "",
            "> 本文件由 `winter_agent_v2/capability_bootstrap.py` 扫描 capability_catalog 生成。",
            "> **Bootstrap 完成 ≠ LIVE_VERIFIED**：这里的最高状态是 "
            f"`{BOOTSTRAP_MAX_LIFECYCLE}`，真机验证仍走统一 Development Validation 流程。",
            "",
            f"- 总表行数：{summary['catalog_rows']}　可预载：{summary['actionable']}"
            f"　已在流程中（禁止重复 Bootstrap）：{summary['in_flight']}",
            f"- 按优先级：{summary['by_priority']}",
            f"- 按计划状态：{summary['by_plan_state']}",
            f"- 按来源：{summary['by_knowledge_source']}",
            "",
        ]
        for plan in (self.candidates()[:limit]):
            lines += [plan.markdown(), ""]
        return "\n".join(lines)


