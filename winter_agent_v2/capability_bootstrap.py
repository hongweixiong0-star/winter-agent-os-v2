@dataclass(frozen=True)
class Facet:
    """One of the seven fields the operator requires before a candidate exists.

    ``value`` is what we know; ``source`` names *where* it came from, so a reader
    can tell the difference between "measured on the current client" and "a
    README says so".  ``UNKNOWN`` is a real answer and the common one -- it is the
    honest input to the next live probe, and it is why a plan can never be
    promoted on knowledge alone.
    """

    name: str
    value: str
    source: str = ""
    confidence: float = 0.0

    @property
    def known(self) -> bool:
        return bool(self.value) and self.value != UNKNOWN

    def as_row(self) -> dict[str, Any]:
        return {
            "field": self.name,
            "value": self.value,
            "source": self.source,
            "confidence": round(self.confidence, 3),
        }


@dataclass(frozen=True)
class BootstrapPlan:
    """One catalog row, classified, de-duplicated, ranked and briefed."""

    capability_id: str
    code: str
    goal: str
    skill: str
    classes: tuple[str, ...]
    priority: str
    score: float
    plan_state: str
    knowledge_source: str
    knowledge_rank: int
    facets: tuple[Facet, ...]
    in_flight: str = ""
    in_flight_reason: str = ""
    risk: str = ""
    unlocked: str = "UNKNOWN"
    existing_skill: str = ""
    has_verifier: bool = False
    missing_semantics: tuple[str, ...] = ()
    reuse: Mapping[str, Any] = field(default_factory=dict)
    external: Mapping[str, Any] = field(default_factory=dict)
    maa: Mapping[str, Any] = field(default_factory=dict)
    targeted_test: Mapping[str, Any] = field(default_factory=dict)
    notes: tuple[str, ...] = ()

    @property
    def actionable(self) -> bool:
        return not self.in_flight

    @property
    def unknown_fields(self) -> tuple[str, ...]:
        return tuple(f.name for f in self.facets if not f.known)

    def as_row(self) -> dict[str, Any]:
        return {
            "capability_id": self.capability_id,
            "code": self.code,
            "goal": self.goal,
            "skill": self.skill,
            "classes": list(self.classes),
            "priority": self.priority,
            "score": round(self.score, 2),
            "plan_state": self.plan_state,
            "knowledge_source": self.knowledge_source,
            "knowledge_rank": self.knowledge_rank,
            "unlocked": self.unlocked,
            "risk": self.risk,
            "existing_skill": self.existing_skill,
            "has_verifier": self.has_verifier,
            "missing_semantics": list(self.missing_semantics),
            "in_flight": self.in_flight,
            "in_flight_reason": self.in_flight_reason,
            "unknown_fields": list(self.unknown_fields),
            "facets": [f.as_row() for f in self.facets],
            "reuse": dict(self.reuse),
            "external": dict(self.external),
            "maa": dict(self.maa),
            "targeted_test": dict(self.targeted_test),
            "notes": list(self.notes),
        }

    def markdown(self) -> str:
        lines = [
            f"### {self.capability_id} · {self.code}",
            "",
            f"- 目标：`{self.goal or '-'}`　技能：`{self.skill or '-'}`　风险：`{self.risk or '-'}`",
            f"- 分类：{', '.join(CLASS_ZH.get(c, c) for c in self.classes)}",
            f"- 优先级：{PRIORITY_ZH.get(self.priority, self.priority)}（score {self.score:.1f}）",
            f"- 计划状态：`{self.plan_state}`　知识来源：{SOURCE_ZH.get(self.knowledge_source, self.knowledge_source)}",
        ]
        if self.in_flight:
            lines.append(f"- **拒绝重复 Bootstrap**：{self.in_flight} — {self.in_flight_reason}")
        lines += ["", "| 字段 | 内容 | 来源 | 置信 |", "|---|---|---|---:|"]
        for facet in self.facets:
            lines.append(
                f"| {facet.name} | {facet.value.replace('|', '/')[:220]} | "
                f"{facet.source or '-'} | {facet.confidence:.2f} |"
            )
        if self.targeted_test:
            lines += ["", f"- Targeted Test：`{self.targeted_test.get('name', '-')}` → "
                          f"{self.targeted_test.get('verdict', '-')}（{self.targeted_test.get('detail', '')[:200]}）"]
        return "\n".join(lines)


